# Math functions
# https://docs.python.org/3/library/math.html

import math

# Constants
print('math.pi:', math.pi)

pi = math.pi

# Rounding
print('round(pi):', round(pi, 2))

pi = round(pi, 2)

# Math functions
print('math.floor(pi):', math.floor(pi))
print('math.ceil(pi):', math.ceil(pi))
print('abs(-4.7):', abs(-4.7))
print('math.sqrt(pi):', math.sqrt(pi))
print('math.pow(pi, 2):', math.pow(pi, 2))

